def parse(name, text):
    rows = text.strip("\n").split("\n")
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise SystemExit(f"{name}: map must be 16x16, got {len(rows)} rows {[len(r) for r in rows]}")
    return rows


def runs(rows, want):
    """Horizontal runs (x, y, w) of pixels for which want(char) is true."""
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < 16:
            if want(row[x]):
                s = x
                while x < 16 and want(row[x]):
                    x += 1
                out.append((s, y, x - s))
            else:
                x += 1
    return out


def path_d(rs):
    return "".join(f"M{x} {y}h{w}v1h-{w}z" for x, y, w in rs)


def svg(body):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" '
            'viewBox="0 0 16 16" shape-rendering="crispEdges">' + body + "</svg>\n")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in ICONS.items():
        rows = parse(name, text)
        d = path_d(runs(rows, lambda c: c == "#"))
        (OUT / f"{name}.svg").write_text(svg(f'<path fill="#ffffff" d="{d}"/>'))
    for name, text in EMBLEMS.items():
        rows = parse(name, text)
        bad = {c for r in rows for c in r} - set(PALETTE) - {"."}
        if bad:
            raise SystemExit(f"{name}: unknown colour letters {bad}")
        body = "".join(
            f'<path fill="{PALETTE[k]}" d="{path_d(runs(rows, lambda c, k=k: c == k))}"/>'
            for k in PALETTE if any(k in r for r in rows))
        (OUT / f"{name}.svg").write_text(svg(body))
    print(f"wrote {len(ICONS) + len(EMBLEMS)} SVGs to {OUT}")


if __name__ == "__main__":
    main()
